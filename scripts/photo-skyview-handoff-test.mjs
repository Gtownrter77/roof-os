import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { embedGpsIntoJpeg, readEmbeddedGps } from '../lib/photo-provenance.mjs'

const read = (path) => readFileSync(new URL('../' + path, import.meta.url), 'utf8')
const jpg = Uint8Array.from([0xff, 0xd8, 0xff, 0xd9])
assert.equal(readEmbeddedGps(jpg), null, 'No embedded coordinates => no photo lookup')
const stamped = embedGpsIntoJpeg(jpg, { latitude: 33.9, longitude: -84.6, address: '123 Example Lane', capturedAt: '2026-11-18T02:00:00Z' })
const gps = readEmbeddedGps(stamped)
assert.ok(gps && Math.abs(gps.latitude - 33.9) < 0.00001)
assert.ok(gps && Math.abs(gps.longitude + 84.6) < 0.00001)

const measure = read('app/measure/page.tsx')
const property = read('app/api/measurements/property/route.ts')
const estimate = read('app/estimate/new/page.tsx')
const estimateApi = read('app/api/estimates/route.ts')
assert.match(measure, /readEmbeddedGps\(new Uint8Array\(bytes\)\)/, 'Read actual selected image bytes')
assert.match(measure, /setPhotoGps\(embedded \?/, 'Location comes from EXIF only')
assert.match(measure, /photoGps\.latitude\.toFixed\(8\)/, 'EXIF precision must fit the safe coordinate URL format')
assert.match(measure, /photoGps\.longitude\.toFixed\(8\)/)
assert.match(measure, /if \(!file \|\| !photoGps\)/, 'GPS-less photo cannot trigger candidate property lookup')
assert.doesNotMatch(measure, /navigator\.geolocation/, 'Never substitute device location for photo EXIF')
assert.match(measure, /candidate property/i, 'Property lookup is not a conclusive match')
assert.match(measure, /setSelectedBuildingIndex\(null\)/, 'A photo must not automatically select a neighboring building')
assert.match(measure, /manual-only and cannot trigger photo automations/, 'No GPS = manual-only')
assert.match(measure, /Continue to estimate draft review/, 'Technician has explicit estimate handoff')
assert.match(measure, /measurementId: savedMeasurementId/, 'Handoff uses saved measurement reference, not user-entered quantities')

assert.match(property, /usingPhotoCoordinates = latParam !== null \|\| lonParam !== null/)
assert.match(property, /if \(membership\.response\) return membership\.response/)
assert.match(property, /reverseUrl\.searchParams\.set\('lat'/)
assert.match(property, /reverseUrl\.searchParams\.set\('lon'/)
assert.match(property, /Photo location address lookup unavailable/)
assert.match(property, /candidateOnly: true/)
assert.match(property, /source: usingPhotoCoordinates \? 'photo_gps_preview' : 'address_search'/)
assert.match(property, /return NextResponse\.json\(\{ address: candidateAddress/, 'Expose only candidate, not validated building match')

assert.match(estimate, /sourceMeasurementId = searchParams\.get\('measurementId'\)/)
assert.match(estimate, /\.eq\('id', sourceMeasurementId\)\.eq\('workspace_id', workspaceId\)/)
assert.match(estimate, /measurement does not belong|Measurement not found in this workspace/i)
assert.match(estimate, /!propertyMatched/, 'User confirms the same property before creating a draft')
assert.match(estimate, /source_measurement_id: sourceMeasurement\?\.id \?\? undefined/)
assert.match(estimate, /not added to estimate line items/i)
assert.match(estimateApi, /body\.source_measurement_id && status !== 'draft'/)
assert.match(estimateApi, /source_measurement_id must be a valid UUID/)
assert.match(estimateApi, /\.eq\('id', body\.source_measurement_id\)\.eq\('workspace_id', workspaceId\)/)
assert.match(estimateApi, /measurement_reference: measurementReference/)
assert.match(estimateApi, /estimate_use: 'human_review_required', priced: false/)
assert.doesNotMatch(estimateApi, /quantity:\s*measurementReference/, 'No unreviewed quantity must become estimate line item')
console.log('Embedded photo skyview and review-only measurement handoff checks passed.')
